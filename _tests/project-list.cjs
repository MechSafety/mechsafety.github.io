const fs = require('node:fs');
const assert = require('node:assert/strict');
const template = fs.readFileSync('projects/index.html', 'utf8');
const css = fs.readFileSync('.design-preview/style-modern.css', 'utf8');
const titleAt = template.indexOf('<h2>{{ item.title }}</h2>');
const metaAt = template.indexOf('<div class="project-meta">');
const agencyAt = template.indexOf('class="project-agency"');
const periodAt = template.indexOf('class="project-period"');
const roleAt = template.indexOf('class="project-role"');
assert.ok(titleAt > 0 && titleAt < metaAt && metaAt < agencyAt && agencyAt < periodAt && periodAt < roleAt);
assert.match(template, /sort: 'start_date' \| reverse/);
assert.match(template, /assign project_image = item\.image \| default: '' \| strip/);
assert.equal((template.match(/if project_image\.size > 0/g) || []).length, 2);
assert.match(template, /loading="lazy"/);
assert.doesNotMatch(template, /project-program|project-funding/);
assert.match(css, /\.project-list\s*\{[^}]*display: block;/);
assert.match(css, /\.project-list\s*\{[^}]*--project-rule-width: min\(1440px, 94%\);[^}]*border-top: 1px solid transparent;/);
assert.match(css, /\.project-item\s*\{[^}]*padding: 16px 6px;[^}]*border: 0;[^}]*border-bottom: 1px solid transparent;[^}]*background: transparent;/);
assert.match(css, /\.project-list::before,\s*\.project-item::after\s*\{[^}]*width: var\(--project-rule-width\);[^}]*height: 1px;/);
assert.match(css, /\.project-copy h2\s*\{[^}]*font-size: 0\.98rem;[^}]*font-weight: 600;/);
assert.match(css, /\.project-meta\s*\{[^}]*flex-wrap: wrap;[^}]*margin: 8px 0 0;[^}]*font-size: 0\.87rem;/);
assert.match(css, /\.project-item\.has-image\s*\{\s*grid-template-columns: minmax\(0, 1fr\) 168px;/);
assert.match(css, /\.project-visual img\s*\{[^}]*object-fit: contain;/);
const mobile = css.slice(css.lastIndexOf('@media (max-width: 720px)'));
assert.match(mobile, /\.project-list\s*\{ --project-rule-width: 100%; \}/);
assert.match(mobile, /\.project-item\.has-image\s*\{[^}]*grid-template-columns: minmax\(0, 1fr\);/);
assert.match(mobile, /\.project-meta > \* \+ \*\s*\{[^}]*border-left: 0;/);
assert.match(mobile, /\.project-visual\s*\{\s*width: min\(168px, 100%\);/);
console.log(JSON.stringify({pass: true, checks: ['title-first compact rows', 'agency year role in one wrapping metadata row', 'thin separators instead of boxes', 'publication-scale typography', 'optional thumbnails only for nonempty images', 'mobile wrapping and small images', 'latest-first order preserved']}));
